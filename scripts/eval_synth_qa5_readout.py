#!/usr/bin/env python
"""Synthetic-qa5 READOUT eval: does the L7 (babilong-shaped) synthetic data have
the SAME difficulty as REAL babilong qa5 for the A-model (step2000, NO training)?

We build a FULLY-FORMATTED babilong-style prompt (same DEFAULT_PROMPTS/template,
same instruction + few-shot + <context>...</context> + Question) whose context is
generated by the SAME event generator the training dataset uses (_qa5b_gen_events
for L7, or the old L6 layout for comparison). PG19 prose is interleaved between
the bAbI sentences so the haystack matches babilong's structure. We then run the
IDENTICAL standard mem-chain generation (generate_with_mem_space) and score with
the OFFICIAL compare_answers — so the number is directly comparable to the real
babilong qa5 standard-mem-chain scores.

RED LINE: never reads any babilong test sample. All context is PG19 + freshly
RNG-generated public-grammar bAbI sentences.

Usage:
  python scripts/eval_synth_qa5_readout.py \
     --checkpoint outputs/mem_space_fifo_b25_c512_supervised_select/full_model_step002000.pt \
     --adapter_config outputs/mem_space_fifo_b25_c512_supervised_select/adapter_config.json \
     --level 7 --target_len 16k --limit 100 --chunk_size 512
"""
import sys, os, re, csv, argparse, random, json, signal
os.environ.setdefault("HF_DATASETS_OFFLINE", "1")
os.environ.setdefault("HF_HUB_OFFLINE", "1")
sys.path.insert(0, "third_party/babilong-pkg")
sys.path.insert(0, "scripts")
sys.path.insert(0, ".")
import numpy as np
import torch
import re as _re

from babilong.prompts import DEFAULT_PROMPTS, DEFAULT_TEMPLATE, get_formatted_input
from babilong.metrics import TASK_LABELS, compare_answers

# Reuse the exact eval model-load + generation path (identical to real babilong).
import importlib.util
_spec = importlib.util.spec_from_file_location("rb", "scripts/run_babilong_mem_space.py")
rb = importlib.util.module_from_spec(_spec); sys.modules["rb"] = rb
_spec.loader.exec_module(rb)

from src.memory.mem_space.niah_chunked_dataset import _qa5b_gen_events

_LEN2TOK = {"2k": 2048, "4k": 4096, "8k": 8192, "16k": 16384, "32k": 32768}


def _decode_prose(tok, bg, rng, n_tokens):
    """Return a continuous-prose string of ~n_tokens from the PG19 bg array."""
    if n_tokens <= 0:
        return ""
    row = rng.randrange(bg.shape[0])
    ids = bg[row, :n_tokens].tolist()
    return tok.decode(ids)


def _coherent_prose_sentences(tok, bg, rng, approx_tokens):
    """Return a list of sentences from ONE contiguous PG19 span (~approx_tokens).

    Real babilong embeds the bAbI facts between the sentences of a SINGLE coherent
    book excerpt. Our earlier version spliced a fresh RANDOM book row per gap ->
    incoherent patchwork that made the model emit list-style answers (never scored
    True). This picks one starting row and reads forward contiguously, then splits
    into sentences so bAbI facts can be interleaved at sentence boundaries.
    """
    if approx_tokens <= 0:
        return []
    n_rows = bg.shape[0]
    row_len = bg.shape[1]
    per_row = row_len
    n_need = max(1, (approx_tokens + per_row - 1) // per_row)
    start = rng.randrange(max(1, n_rows - n_need))
    ids = []
    for r in range(start, min(n_rows, start + n_need)):
        ids.extend(int(x) for x in bg[r].tolist())
        if len(ids) >= approx_tokens:
            break
    text = tok.decode(ids[:approx_tokens])
    # split into sentences (keep terminators)
    sents = _re.split(r'(?<=[.!?])\s+', text)
    return [s.strip() for s in sents if s.strip()]


def build_synth_context(tok, bg, rng, level, target_tokens, chunk_size):
    """Build a babilong-shaped haystack STRING + (question, answer).

    L7: use _qa5b_gen_events (recency, entity recurrence, end-biased needle),
        interleave the bAbI facts between the sentences of ONE coherent PG19 book
        excerpt (exactly babilong's method), at positions matching the events'
        temporal fractions.
    L6: old layout — a single needle + a few clean template distractors placed
        near the front; ONE coherent PG19 excerpt fills the rest (the CURRENT
        synthetic's cleaner structure).
    """
    n_ctx = max(1, round(target_tokens / chunk_size))
    if level == 7:
        # FIXED ~15 events (babilong median) independent of length (only prose grows).
        target_events = max(4, rng.randint(12, 18) if n_ctx >= 4 else n_ctx)
        giver, obj, question, answer, placed = _qa5b_gen_events(rng, target_events)
        # (fraction, sentence) list in temporal order
        facts = [(p, s) for p, s, _ in placed]
    else:  # level 6 — emulate the CURRENT synthetic layout (restricted label vocab)
        AG = ["Bill", "Fred", "Jeff", "Mary"]
        OB = ["apple", "football", "milk"]
        VB = ["gave", "handed", "passed"]
        g, r = rng.sample(AG, 2)
        obj = rng.choice(OB); verb = rng.choice(VB)
        giver, answer, question = g, r, f"Who did {g} give the {obj} to?"
        needle = f"{g} {verb} the {obj} to {r}."
        wrong = [a for a in AG if a not in (g, r)]; rng.shuffle(wrong)
        o2 = rng.choice([o for o in OB if o != obj])
        rooms = ["garden", "kitchen", "office", "bedroom", "hallway", "bathroom"]
        while len(wrong) < 3:
            wrong.append(rng.choice(AG))
        distract = [
            f"{g} {rng.choice(VB)} the {o2} to {wrong[0]}.",
            f"{wrong[1]} {rng.choice(VB)} the {obj} to {wrong[2]}.",
            f"{g} went back to the {rng.choice(rooms)}.",
            f"{wrong[0]} journeyed to the {rng.choice(rooms)}.",
        ]
        # L6: needle near the front (chunk-0), a few clean distractors spread after.
        facts = [(0.02, needle)]
        for k, d in enumerate(distract):
            facts.append((0.15 + 0.2 * k, d))
        facts.sort()

    # ONE coherent PG19 excerpt, split into sentences; interleave facts at their
    # fractional positions (babilong's method: facts between real book sentences).
    babi_tok = sum(len(tok.encode(" " + s, add_special_tokens=False)) for _, s in facts)
    prose = _coherent_prose_sentences(tok, bg, rng, max(0, target_tokens - babi_tok))
    n_prose = len(prose)
    if n_prose == 0:
        merged = [s for _, s in facts]
    else:
        # assign each fact an insertion index into the prose-sentence list by fraction
        merged = list(prose)
        # insert from the end so earlier indices stay valid
        for frac, s in sorted(facts, key=lambda t: t[0], reverse=True):
            idx = min(n_prose, max(0, int(frac * n_prose)))
            merged.insert(idx, s)
    context = " ".join(merged).strip()
    return context, question, answer


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--checkpoint", required=True)
    ap.add_argument("--adapter_config", required=True)
    ap.add_argument("--model_path", default="models/Meta-Llama-3-8B")
    ap.add_argument("--background", default="data/pg19_chunks_llama3_noeos.npy")
    ap.add_argument("--level", type=int, default=7)
    ap.add_argument("--target_len", default="16k")
    ap.add_argument("--limit", type=int, default=100)
    ap.add_argument("--chunk_size", type=int, default=512)
    ap.add_argument("--max_new_tokens", type=int, default=20)
    ap.add_argument("--seed", type=int, default=1234)
    ap.add_argument("--sample_timeout", type=int, default=90,
                    help="per-sample wall-clock cap (s); SIGALRM-skip a sample that "
                         "exceeds it (counts wrong) so one pathological sample never "
                         "blocks the shard. 0 = disable.")
    ap.add_argument("--shard_index", type=int, default=0)
    ap.add_argument("--num_shards", type=int, default=1)
    ap.add_argument("--readerattn_topk", type=int, default=0,
                    help="reader-attn token selection top-k. 0 = pure last-chunk "
                         "'standard mem-chain' (no selector; matches the report's "
                         "'无selector端到端' definition). >0 = deployable reader-attn "
                         "chunk selection + token reforward (select_layer=16 topk=2 "
                         "is what the a2000_loc probe logs used).")
    ap.add_argument("--readerattn_select_layer", type=int, default=16)
    ap.add_argument("--real_babilong", action="store_true",
                    help="ANALYSIS/CONTROL ONLY: run the IDENTICAL path on REAL "
                         "babilong qa5 (eval, never trained on) to calibrate whether "
                         "this harness reproduces the known A-model score. Ignores "
                         "--level; loads the babilong arrow cache for --target_len.")
    ap.add_argument("--out_csv", default="")
    ap.add_argument("--dtype", default="bfloat16")
    args = ap.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = {"bfloat16": torch.bfloat16, "float16": torch.float16,
             "float32": torch.float32}[args.dtype]
    target_tokens = _LEN2TOK[args.target_len]

    with open(args.adapter_config) as f:
        adapter_cfg = json.load(f)
    mem_config = rb.build_mem_space_config(adapter_cfg)
    print(f"[synth-eval] level={args.level} len={args.target_len}({target_tokens}tok) "
          f"chunk={args.chunk_size} bg={args.background} limit={args.limit}")
    model = rb.load_mem_space_model(args.model_path, args.checkpoint, mem_config,
                                    device, dtype=dtype)
    model.eval()

    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(args.model_path)
    bg = np.load(args.background, mmap_mode="r")
    if bg.ndim == 1:
        # flat token stream -> reshape into rows of chunk length for _decode_prose
        L = target_tokens
        n = bg.shape[0] // L
        bg = bg[: n * L].reshape(n, L)

    prompt_cfg = dict(DEFAULT_PROMPTS["qa5"])
    prompt_cfg["template"] = DEFAULT_TEMPLATE
    labels = TASK_LABELS["qa5"]

    # CONTROL: real babilong qa5 through the IDENTICAL harness path (analysis only).
    real_ds = None
    if args.real_babilong:
        data = rb.load_babilong_dataset("RMT-team/babilong", args.target_len)
        # DatasetDict keyed by task name -> take the qa5 split.
        real_ds = data["qa5"] if isinstance(data, dict) or hasattr(data, "keys") else data
        print(f"[synth-eval] REAL babilong qa5 {args.target_len} CONTROL: {len(real_ds)} rows")

    idxs = list(range(args.limit))[args.shard_index::args.num_shards]
    rows = []
    correct = 0
    for j, i in enumerate(idxs):
        rng = random.Random(args.seed * 100003 + i)
        if real_ds is not None:
            rec = real_ds[i]
            context, question, answer = rec["input"], rec["question"], rec["target"]
        else:
            context, question, answer = build_synth_context(
                tok, bg, rng, args.level, target_tokens, args.chunk_size)
        input_text = get_formatted_input(
            context, question, prompt_cfg["examples"], prompt_cfg["instruction"],
            prompt_cfg["post_prompt"], template=prompt_cfg["template"])
        ids = tok.encode(input_text, add_special_tokens=True, return_tensors="pt").to(device)
        n_chunks = (ids.shape[1] + args.chunk_size - 1) // args.chunk_size
        # Per-sample wall-clock guard: a rare pathological sample can make the
        # streaming forward extremely slow; SIGALRM-skip it (count wrong) so one
        # sample never blocks the whole shard. 0 disables.
        class _Timeout(Exception):
            pass

        def _alarm(signum, frame):
            raise _Timeout()

        out = "[SKIP-TIMEOUT]"
        if args.sample_timeout > 0:
            signal.signal(signal.SIGALRM, _alarm)
            signal.alarm(args.sample_timeout)
        try:
            with torch.amp.autocast(device_type="cuda", dtype=dtype):
                out = rb.generate_with_mem_space(
                    model=model, input_ids=ids, tokenizer=tok,
                    chunk_size=args.chunk_size, max_new_tokens=args.max_new_tokens,
                    device=device, swa_eval_chunks=0,
                    readerattn_token=(args.readerattn_topk > 0),
                    readerattn_select_layer=args.readerattn_select_layer,
                    readerattn_topk=args.readerattn_topk)
        except _Timeout:
            print(f"  [{j+1}/{len(idxs)}] SAMPLE TIMEOUT (>{args.sample_timeout}s) — skipped",
                  flush=True)
        finally:
            if args.sample_timeout > 0:
                signal.alarm(0)
        ok = compare_answers(answer, out, question, labels)
        correct += int(ok)
        rows.append((answer, out, question, int(ok), int(n_chunks), int(ids.shape[1])))
        if j < 6 or j % 5 == 0:
            print(f"  [{j+1}/{len(idxs)}] len={ids.shape[1]}tok nchunks={n_chunks} "
                  f"gold={answer!r} pred={out.strip()[:30]!r} ok={ok} run={correct}/{j+1}",
                  flush=True)

    acc = 100.0 * correct / max(1, len(idxs))
    print(f"\n[synth-eval] LEVEL {args.level} qa5 {args.target_len} standard-mem-chain: "
          f"{correct}/{len(idxs)} = {acc:.1f}")
    if args.out_csv:
        os.makedirs(os.path.dirname(args.out_csv) or ".", exist_ok=True)
        with open(args.out_csv, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["target", "output", "question", "correct", "n_chunks", "n_tokens"])
            w.writerows(rows)
        print(f"[synth-eval] wrote {args.out_csv}")


if __name__ == "__main__":
    main()
